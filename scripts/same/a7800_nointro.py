"""
libretro-same: generates src/devices/bus/a7800/a78_nointro.h, the table that lets
same_a7800 load No-Intro ROMs (.bin files without the 128-byte .a78 header) and fixes
.a78 files whose header has the wrong mapper.

No-Intro gives the CRC32, MD5 and name of each ROM (without header), but not its
mapper. ProSystem's database gives the cart type of each ROM by the same MD5. This
script joins both by MD5 and writes the CRC32, the MAME mapper value (bytes 53-54 of
the .a78 header) and whether the ROM is PAL. When MAME's software list (hash/a7800.xml)
has the same ROM, its mapper wins over ProSystem's.

Usage:
  python3 scripts/same/a7800_nointro.py "Atari - 7800.dat" Database.c \
      src/devices/bus/a7800/a78_nointro.h

  "Atari - 7800.dat": https://github.com/libretro/libretro-database/blob/master/metadat/no-intro/Atari%20-%207800.dat
  Database.c:         https://github.com/libretro/prosystem-libretro/blob/master/core/Database.c
"""

import os
import re
import sys

# ProSystem cart type -> MAME .a78 header mapper (bytes 53-54)
PROSYSTEM_TO_MAME = {
	0: 0x0000,  # normal                      -> a78_rom
	1: 0x0002,  # SuperCart                   -> a78_sg
	2: 0x000a,  # SuperCart large (144K)      -> a78_sg9
	3: 0x0006,  # SuperCart + RAM at $4000    -> a78_sg_ram
	4: 0x0002,  # SuperCart + bank 6 at $4000 -> a78_sg (MAME always maps bank 6 there)
	5: 0x0200,  # Absolute                    -> a78_abs
	6: 0x0100,  # Activision                  -> a78_act
}
POKEY_4000 = 0x0001

# MAME software list slot -> MAME .a78 header mapper (bytes 53-54)
SLOT_TO_MAME = {
	'a78_rom':      0x0000,
	'a78_pokey':    0x0001,
	'a78_sg':       0x0002,
	'a78_sg_pokey': 0x0003,
	'a78_sg_ram':   0x0006,
	'a78_sg9':      0x000a,
	'a78_mram':     0x0080,
	'a78_act':      0x0100,
	'a78_abs':      0x0200,
}

def read_softlist(path):
	"""Returns {crc: slot} for the single-ROM entries of MAME's hash/a7800.xml."""
	text = open(path, encoding='utf-8').read()
	slots = {}
	for body in re.findall(r'<software name="[^"]+"[^>]*>(.*?)</software>', text, re.S):
		roms = re.findall(r'<rom name="[^"]*" size="[^"]+" crc="([0-9a-f]+)"', body)
		slot = re.search(r'<feature name="slot" value="([^"]+)"', body)
		if len(roms) == 1:
			slots[int(roms[0], 16)] = slot.group(1) if slot else 'a78_rom'
	return slots

def read_nointro(path):
	"""Returns {md5: (name, size, crc)} for the ROMs without header (.bin)."""
	text = open(path, encoding='utf-8').read()
	roms = {}
	for name, size, crc, md5 in re.findall(r'rom \( name "([^"]+)" size (\d+) crc (\w+) md5 (\w+)', text):
		if name.lower().endswith('.bin'):
			roms[md5.lower()] = (name[:-4], int(size), int(crc, 16))
	return roms

def read_prosystem(path):
	"""Returns {md5: (type, pokey, pokey_address, region)}."""
	text = open(path, encoding='utf-8').read()
	db = {}
	for block in re.findall(r'\{\s*"[0-9a-f]{32}".*?\}', text, re.S):
		md5 = re.search(r'"([0-9a-f]{32})"', block).group(1)
		# "2,   /* type */" or "2,   /* type: SUPERCART_LARGE */"
		fields = dict((k.strip(), v) for v, k in re.findall(r'(-?\w+),?\s*/\* ([\w ]+?)(?::[^*]*)? \*/', block))
		db[md5] = (int(fields['type']), fields['pokey'] == 'true',
				int(fields.get('pokey_address', '0'), 0), int(fields['region']))
	return db

def main():
	if len(sys.argv) != 4:
		sys.exit(__doc__)
	nointro = read_nointro(sys.argv[1])
	prosystem = read_prosystem(sys.argv[2])
	softlist = read_softlist(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'hash', 'a7800.xml'))

	entries = []
	skipped = []
	for md5, (name, size, crc) in nointro.items():
		if md5 not in prosystem:
			skipped.append((name, 'not in ProSystem database'))
			continue
		cart_type, pokey, pokey_address, region = prosystem[md5]
		if cart_type not in PROSYSTEM_TO_MAME or pokey_address not in (0, 0x4000):
			skipped.append((name, 'cart type %d / POKEY at $%04x not in MAME' % (cart_type, pokey_address)))
			continue
		mapper = PROSYSTEM_TO_MAME[cart_type] | (POKEY_4000 if pokey else 0)
		# MAME's software list (dumps of the real carts) wins over ProSystem's database
		slot = softlist.get(crc)
		if slot in SLOT_TO_MAME and SLOT_TO_MAME[slot] != mapper:
			print('%s: ProSystem 0x%04x, software list %s (0x%04x): using the software list'
					% (name, mapper, slot, SLOT_TO_MAME[slot]))
			mapper = SLOT_TO_MAME[slot]
		entries.append((name, crc, mapper, 1 if region == 1 else 0))

	with open(sys.argv[3], 'w', newline='\n') as out:
		out.write('// license:BSD-3-Clause\n')
		out.write('// Generated by scripts/same/a7800_nointro.py - do not edit.\n')
		out.write('//\n')
		out.write('// libretro-same: mapper and region of the ROMs in No-Intro\'s "Atari - 7800" set,\n')
		out.write('// identified by the CRC32 of the ROM without the 128-byte .a78 header.\n')
		out.write('// Sources: No-Intro (libretro-database) for the CRC32 and names, and the database of\n')
		out.write('// ProSystem (libretro/prosystem-libretro, GPLv2) for the cart types.\n')
		out.write('\n')
		out.write('#ifndef MAME_BUS_A7800_A78_NOINTRO_H\n')
		out.write('#define MAME_BUS_A7800_A78_NOINTRO_H\n')
		out.write('\n')
		out.write('#pragma once\n')
		out.write('\n')
		out.write('struct a78_nointro_entry\n')
		out.write('{\n')
		out.write('\tuint32_t crc;      // CRC32 of the ROM without header\n')
		out.write('\tuint16_t mapper;   // .a78 header bytes 53-54\n')
		out.write('\tuint8_t pal;       // 1 = PAL, 0 = NTSC\n')
		out.write('};\n')
		out.write('\n')
		out.write('static const a78_nointro_entry a78_nointro[] =\n')
		out.write('{\n')
		for name, crc, mapper, pal in sorted(entries, key=lambda e: e[0].lower()):
			out.write('\t{ 0x%08x, 0x%04x, %d },   // %s\n' % (crc, mapper, pal, name))
		out.write('};\n')
		out.write('\n')
		out.write('#endif // MAME_BUS_A7800_A78_NOINTRO_H\n')

	print('%d entries written to %s' % (len(entries), sys.argv[3]))
	for name, reason in sorted(skipped):
		if 'Aftermarket' not in name and 'Unl' not in name:
			print('skipped: %s (%s)' % (name, reason))
	print('skipped %d homebrew ROMs (Aftermarket/Unl)' % sum(1 for n, r in skipped if 'Aftermarket' in n or 'Unl' in n))

if __name__ == '__main__':
	main()
